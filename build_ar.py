#!/usr/bin/env python3
"""
Builds ar.html (static Arabic page) from index.html.

Source of truth: index.html. Every translatable element carries data-en and data-ar.
This script copies index.html, writes each element's data-ar value into the page body
as real text (so Google can read it), flips the page to lang="ar" dir="rtl", and
updates title, description, canonical, hreflang and sitemap.xml.

Run:  python build_ar.py      (GitHub Action does it automatically on every push)
Never edit ar.html by hand. It is overwritten on every run.
"""
import datetime
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SITE = "https://2020tiamo2020-del.github.io/Tiamo-Mohamad-Portfolio-ULTIMATE/"
EN_URL = SITE
AR_URL = SITE + "ar.html"

AR_TITLE = "تيامو محمد | فنان ذكاء اصطناعي ومصمم فوتوشوب وصانع فيديو"
AR_DESC = ("تيامو محمد فنان ذكاء اصطناعي ومصمم فوتوشوب وصانع فيديو وVFX. "
           "يصنع مرئيات سينمائية ودمج صور وريلز وتصميم مواقع وأغلفة كتب وتجارب رقمية إبداعية.")
AR_OG_DESC = ("فنان ذكاء اصطناعي ومصمم فوتوشوب وصانع فيديو وVFX. "
              "مرئيات سينمائية وتصميم مواقع وأغلفة كتب وتجارب رقمية إبداعية.")
AR_OG_ALT = "تيامو محمد، فنان ذكاء اصطناعي ومصمم فوتوشوب وصانع فيديو"

NOTE = (
    "<!-- AI NOTE: this site has TWO language versions. index.html is the only file you edit. "
    "Each text element has data-en and data-ar: update BOTH (and the visible English text). "
    "ar.html is generated by build_ar.py, never edit it by hand. See AGENTS.md. -->"
)

HEAD_RE = re.compile(r"<!-- TM-I18N-HEAD:BEGIN.*?TM-I18N-HEAD:END -->\s*", re.S)
TAIL_RE = re.compile(r"<!-- TM-I18N-TAIL:BEGIN.*?TM-I18N-TAIL:END -->\s*", re.S)
OLD_LANG_SCRIPT_RE = re.compile(
    r"<script>\(function\(\)\{try\{var q=new URLSearchParams\(location\.search\)\.get\(\"lang\"\).*?</script>\s*",
    re.S,
)

START = re.compile(
    r"<(?P<tag>[A-Za-z][\w:-]*)"
    r"(?P<attrs>(?:\s+[^\s\"'<>/=]+(?:\s*=\s*(?:\"[^\"]*\"|'[^']*'|[^\s\"'=<>`]+))?)*)"
    r"\s*/?>"
)
ATTR_AR = re.compile(r"\sdata-ar\s*=\s*(?:\"([^\"]*)\"|'([^']*)')")
LONE_AMP = re.compile(r"&(?![A-Za-z][A-Za-z0-9]*;|#\d+;|#x[0-9A-Fa-f]+;)")


def head_block(lang):
    other = "ar_AR" if lang == "en" else "en_US"
    own = "en_US" if lang == "en" else "ar_AR"
    canonical = EN_URL if lang == "en" else AR_URL
    return (
        "<!-- TM-I18N-HEAD:BEGIN (generated by build_ar.py, do not edit by hand) -->\n"
        + NOTE + "\n"
        f'<link rel="canonical" href="{canonical}">\n'
        f'<link rel="alternate" hreflang="en" href="{EN_URL}">\n'
        f'<link rel="alternate" hreflang="ar" href="{AR_URL}">\n'
        f'<link rel="alternate" hreflang="x-default" href="{EN_URL}">\n'
        f'<meta property="og:locale" content="{own}">\n'
        f'<meta property="og:locale:alternate" content="{other}">\n'
        f'<script>try{{localStorage.setItem("tiamo-lang","{lang}")}}catch(e){{}}</script>\n'
        "<!-- TM-I18N-HEAD:END -->\n"
    )


def tail_block(target):
    return (
        "<!-- TM-I18N-TAIL:BEGIN (generated by build_ar.py, do not edit by hand) -->\n"
        '<script>(function(){var b=document.getElementById("langBtn");if(!b)return;'
        'b.addEventListener("click",function(e){e.preventDefault();e.stopImmediatePropagation();'
        f'location.href="{target}"}},true)}})()</script>\n'
        "<!-- TM-I18N-TAIL:END -->\n"
    )


def patch_english(src):
    s = HEAD_RE.sub("", src)
    s = TAIL_RE.sub("", s)
    s = re.sub(r'<link rel="canonical"[^>]*>\s*', "", s)
    s = re.sub(r'<link rel="alternate" hreflang=[^>]*>\s*', "", s)
    s = OLD_LANG_SCRIPT_RE.sub("", s)
    if "</head>" not in s or "</body>" not in s:
        sys.exit("index.html has no </head> or </body>")
    s = s.replace("</head>", head_block("en") + "</head>", 1)
    s = s.replace("</body>", tail_block("ar.html") + "</body>", 1)
    return s


def find_close(s, i, tag):
    pat = re.compile(r"<(/?)%s(?=[\s/>])" % re.escape(tag), re.I)
    depth = 1
    for m in pat.finditer(s, i):
        if m.group(1):
            depth -= 1
            if depth == 0:
                return m.start()
        else:
            sm = START.match(s, m.start())
            if sm and not sm.group(0).endswith("/>"):
                depth += 1
    return None


def swap_text(s):
    protected = [m.span() for m in re.finditer(r"<(script|style)\b.*?</\1\s*>", s, re.S | re.I)]

    def inside(i):
        return any(a <= i < b for a, b in protected)

    out, pos, count, skipped = [], 0, 0, 0
    for m in START.finditer(s):
        if m.start() < pos or inside(m.start()):
            continue
        am = ATTR_AR.search(m.group("attrs"))
        if not am or m.group(0).endswith("/>"):
            continue
        end = find_close(s, m.end(), m.group("tag"))
        if end is None:
            skipped += 1
            continue
        raw = am.group(1) if am.group(1) is not None else am.group(2)
        value = LONE_AMP.sub("&amp;", html.unescape(raw))
        out.append(s[pos:m.end()])
        out.append(value)
        pos = end
        count += 1
    out.append(s[pos:])
    return "".join(out), count, skipped


def set_meta(s, attr, key, value):
    pat = re.compile(r'(<meta\s+%s="%s"\s+content=")[^"]*(")' % (attr, re.escape(key)))
    new, n = pat.subn(lambda m: m.group(1) + html.escape(value, quote=True) + m.group(2), s, count=1)
    if n == 0:
        print("warning: meta tag not found:", key)
    return new


def to_arabic(en):
    s = HEAD_RE.sub(lambda m: head_block("ar"), en, count=1)
    s = TAIL_RE.sub(lambda m: tail_block("./"), s, count=1)
    s, n = re.subn(r'<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">', s, count=1)
    if n == 0:
        print("warning: <html lang=en dir=ltr> not found")
    s, count, skipped = swap_text(s)
    s = re.sub(r"<title>.*?</title>", "<title>%s</title>" % html.escape(AR_TITLE, quote=False), s, count=1, flags=re.S)
    s = set_meta(s, "name", "description", AR_DESC)
    s = set_meta(s, "property", "og:title", AR_TITLE)
    s = set_meta(s, "property", "og:description", AR_OG_DESC)
    s = set_meta(s, "property", "og:url", AR_URL)
    s = set_meta(s, "property", "og:image:alt", AR_OG_ALT)
    s = set_meta(s, "name", "twitter:title", AR_TITLE)
    s = set_meta(s, "name", "twitter:description", AR_OG_DESC)
    return s, count, skipped


def sitemap():
    today = datetime.date.today().isoformat()
    alt = (
        f'    <xhtml:link rel="alternate" hreflang="en" href="{EN_URL}"/>\n'
        f'    <xhtml:link rel="alternate" hreflang="ar" href="{AR_URL}"/>\n'
        f'    <xhtml:link rel="alternate" hreflang="x-default" href="{EN_URL}"/>\n'
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
        'xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        f"  <url>\n    <loc>{EN_URL}</loc>\n    <lastmod>{today}</lastmod>\n{alt}  </url>\n"
        f"  <url>\n    <loc>{AR_URL}</loc>\n    <lastmod>{today}</lastmod>\n{alt}  </url>\n"
        "</urlset>\n"
    )


def write_if_changed(path, text):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != text:
        path.write_text(text, encoding="utf-8")
        print("updated:", path.name)
    else:
        print("unchanged:", path.name)


def main():
    src_path = ROOT / "index.html"
    src = src_path.read_text(encoding="utf-8")
    if "data-ar=" not in src:
        sys.exit("No data-ar attributes found in index.html")
    en = patch_english(src)
    ar, count, skipped = to_arabic(en)
    write_if_changed(src_path, en)
    write_if_changed(ROOT / "ar.html", ar)
    write_if_changed(ROOT / "sitemap.xml", sitemap())
    print(f"Arabic text written into {count} elements" + (f", {skipped} skipped (no closing tag)" if skipped else ""))


if __name__ == "__main__":
    main()
