  /* rich text: bold + safe links only */
  function rich(node, text) {
    node.textContent = "";
    String(text).split(/(\*\*[^*\n]+\*\*|https?:\/\/[^\s<>"')\]]+)/g).forEach(function (part) {
      if (!part) return;
      if (/^\*\*[^*]+\*\*$/.test(part)) { var b = document.createElement("b"); b.textContent = part.slice(2, -2); node.appendChild(b); }
      else if (/^https?:\/\//.test(part)) {
        var tail = (part.match(/[.,;:!?؟،]+$/) || [""])[0], url = part.slice(0, part.length - tail.length);
        var a = document.createElement("a"); a.href = url; a.target = "_blank"; a.rel = "noopener noreferrer"; a.textContent = url.replace(/^https?:\/\/(www\.)?/, "");
        node.appendChild(a); if (tail) node.appendChild(document.createTextNode(tail));
      } else node.appendChild(document.createTextNode(part));
    });
  }
